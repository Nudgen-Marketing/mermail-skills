import sys
import json
import urllib.request
import math

COINS = ("solana", "bitcoin", "ethereum")
MAX_RESPONSE_BYTES = 512_000

def scrape_market_data():
    """Scrapes live market indicators for the digest."""
    url = "https://api.coingecko.com/api/v3/simple/price?ids=solana,bitcoin,ethereum&vs_currencies=usd&include_24hr_change=true"
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            raw = resp.read(MAX_RESPONSE_BYTES + 1)
            if len(raw) > MAX_RESPONSE_BYTES:
                return {"error": "market_response_too_large"}
            data = json.loads(raw.decode('utf-8'))
            return data
    except Exception:
        return {"error": "market_fetch_failed"}

def format_digest(data):
    """Formats raw market data into clean Markdown for Mermail."""
    if not isinstance(data, dict) or "error" in data:
        raise ValueError("market_data_unavailable")
    for coin in COINS:
        info = data.get(coin)
        if not isinstance(info, dict):
            raise ValueError("market_data_incomplete")
        for field in ("usd", "usd_24h_change"):
            value = info.get(field)
            try:
                finite = not isinstance(value, bool) and isinstance(value, (int, float)) and math.isfinite(value)
            except OverflowError:
                finite = False
            if not finite:
                raise ValueError("market_data_invalid_number")
        if info["usd"] < 0:
            raise ValueError("market_data_invalid_price")
    digest = "## 📊 Daily Web Scraping & Crypto Market Digest\n\n"
    digest += "*Generated by Mermail Scraping Agent Skill*\n\n"
    for coin in COINS:
        info = data[coin]
        price = info['usd']
        change = info['usd_24h_change']
        emoji = "📈" if change >= 0 else "📉"
        digest += f"- **{coin.upper()}**: ${price:,.2f} ({emoji} {change:+.2f}% 24h)\n"
    digest += "\n---\n*Prepared from a public market-data response; not sent. Source freshness is not independently verified.*"
    return digest

def send_to_mermail(digest_text, recipient_inbox):
    """Report the unimplemented adapter; this function never sends email."""
    return {"status": "blocked", "delivered": False,
            "reason": "mermail_dispatch_not_implemented",
            "recipient": recipient_inbox, "digest": digest_text}

if __name__ == "__main__":
    if len(sys.argv) != 2 or not sys.argv[1].strip():
        print(json.dumps({"status": "blocked", "delivered": False,
                          "reason": "explicit_recipient_required"}))
        sys.exit(2)
    try:
        digest = format_digest(scrape_market_data())
    except (ValueError, OverflowError):
        print(json.dumps({"status": "blocked", "delivered": False,
                          "reason": "market_data_unavailable_or_invalid"}))
        sys.exit(2)
    print(json.dumps(send_to_mermail(digest, sys.argv[1])))
    sys.exit(3)  # An intended delivery did not occur; never report success.
